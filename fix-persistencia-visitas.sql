-- 2) FIX 1: usuarios.id autoincremental -------------------------------------
-- Convierte la columna a IDENTITY si aún no lo es. La fila existente (id=0)
-- se conserva; la secuencia queda alineada para que el próximo registro
-- reciba el siguiente id libre (1, 2, 3...).
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'usuarios'
      AND column_name = 'id'
      AND is_identity = 'NO'
      AND data_type IN ('smallint', 'integer', 'bigint')
  ) THEN
    ALTER TABLE usuarios ALTER COLUMN id DROP DEFAULT;
    ALTER TABLE usuarios ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    RAISE NOTICE 'usuarios.id convertida a IDENTITY OK';
  ELSE
    RAISE NOTICE 'usuarios.id ya es identity (o no es numérica): sin cambios';
  END IF;

  -- Alinear la secuencia por encima del id máximo existente
  IF pg_get_serial_sequence('public.usuarios', 'id') IS NOT NULL THEN
    PERFORM setval(
      pg_get_serial_sequence('public.usuarios', 'id'),
      GREATEST((SELECT COALESCE(MAX(id), 0) FROM usuarios) + 1, 1),
      false
    );
    RAISE NOTICE 'Secuencia de usuarios.id alineada';
  END IF;
END $$;

-- 3) FIX 2: unicidad "una visita por usuario+stand" --------------------------
-- Garantía de dominio (el app sólo sella una vez por stand) y además hace
-- idempotente la sincronización: el frontend tolera el error 23505 como
-- "ya existía". Sólo se crea si NO hay filas duplicadas.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.table_constraints
    WHERE table_schema = 'public'
      AND table_name = 'visitas_estaciones'
      AND constraint_name = 'uq_visitas_usuario_stand'
  ) THEN
    IF EXISTS (
      SELECT usuario_id, stand_codigo FROM visitas_estaciones
      GROUP BY usuario_id, stand_codigo HAVING COUNT(*) > 1
    ) THEN
      RAISE WARNING 'Hay visitas duplicadas: limpiarlas antes de crear la UNIQUE (no se creó)';
    ELSE
      ALTER TABLE visitas_estaciones
        ADD CONSTRAINT uq_visitas_usuario_stand UNIQUE (usuario_id, stand_codigo);
      RAISE NOTICE 'UNIQUE uq_visitas_usuario_stand creada';
    END IF;
  ELSE
    RAISE NOTICE 'UNIQUE de visitas ya existía';
  END IF;
END $$;

